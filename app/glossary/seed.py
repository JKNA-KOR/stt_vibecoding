_ALWAYS_HINT_PRIORITY: Final = 1000


def _priority_for(term: str, category: str) -> int:
    """전사 힌트에 실릴 순서를 정한다.

    핵심 용어를 맨 앞에 세우고, 나머지는 분류 우선순위를 따른다. 힌트에 못 들어간
    용어도 분석·QA 프롬프트에는 뜻과 함께 그대로 들어간다 — 우선순위가 낮다고 쓸모가
    없는 것은 아니다.
    """
    if term in _ALWAYS_HINT:
        return _ALWAYS_HINT_PRIORITY
    return _CATEGORY_PRIORITY.get(category, _DEFAULT_PRIORITY)


def seed_payloads(default_priority: int | None = None) -> list[dict[str, object]]:
    """기본 용어를 등록용 형태로 만든다.

    `default_priority` 를 주면 분류별 우선순위 대신 그 값을 일괄 적용한다. 테스트가
    우선순위 규칙과 무관하게 목록만 확인할 때 쓴다.
    """
    return [
        {
            "term": term,
            "category": category,
            "definition": definition,
            "aliases": list(aliases),
            "priority": (
                default_priority
                if default_priority is not None
                else _priority_for(term, category)
            ),
        }
        for term, category, definition, aliases in SEED_TERMS
    ]

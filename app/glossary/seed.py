def _deduplicate() -> tuple[_Term, ...]:
    """분류가 겹쳐 같은 용어가 두 번 실리는 것을 막는다.

    용어는 DB 에서 유일해야 하므로, 중복이 있으면 `load_seed` 가 뒤엣것을 조용히 건너뛴다.
    그러면 "왜 이 분류에는 안 들어갔지"가 되므로 여기서 먼저 걸러 낸다.
    """
    seen: set[str] = set()
    unique: list[_Term] = []
    for group in _GROUPS:
        for term in group:
            if term[0] in seen:
                continue
            seen.add(term[0])
            unique.append(term)
    return tuple(unique)



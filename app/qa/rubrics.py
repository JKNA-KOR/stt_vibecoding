def rubric_fingerprint(text: str) -> str:
    """루브릭 본문의 짧은 해시.

    평가 결과와 함께 저장해 "어떤 기준으로 매긴 점수인가"에 답한다 (Harness §20).
    본문 자체를 결과마다 복사해 두면 저장 비용이 크고, 버전 번호만 두면 운영자가
    본문을 고쳤을 때 그대로 남는다 — 내용에서 유도되는 값이어야 한다.
    """
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]
